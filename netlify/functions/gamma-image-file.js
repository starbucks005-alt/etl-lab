/* gamma-image-file — serve a generated portrait.
   GET ?id=byoa-... -> image/png

   Historical family name, see gamma-image-ask.js. Portraits are generated by
   us now rather than fetched from a third party, so they live in the
   byoa_portraits blob store and need an endpoint of their own.
*/

const { getStore, connectLambda } = require('@netlify/blobs');

exports.handler = async function (event) {
  const id = (event.queryStringParameters && event.queryStringParameters.id) || '';
  if (!/^byoa-[0-9a-z-]+$/i.test(id)) return { statusCode: 400, body: 'id required' };

  try { connectLambda(event); } catch (_) {}

  let buf;
  try {
    const store = getStore('byoa_portraits');
    buf = await store.get(id + '.png', { type: 'arrayBuffer' });
    if (!buf) return { statusCode: 404, body: 'not found' };
  } catch (e) {
    console.error('[gamma-image-file] read failed', e && e.message);
    return { statusCode: 500, body: 'store unavailable' };
  }

  // A base64 body has a hard ceiling around 6MB and going over returns a bare
  // 502 with no explanation. Say so plainly instead of letting the platform
  // swallow it, which is how an oversized ETL Design render hid earlier today.
  if (buf.byteLength > 4 * 1024 * 1024) {
    console.error('[gamma-image-file] portrait too large to serve: ' + buf.byteLength + ' bytes for ' + id);
    return { statusCode: 413, body: 'portrait too large' };
  }

  return {
    statusCode: 200,
    headers: {
      'Content-Type': 'image/png',
      // A given portrait never changes; a regeneration is a new id.
      'Cache-Control': 'public, max-age=31536000, immutable',
      'Access-Control-Allow-Origin': '*',
    },
    body: Buffer.from(buf).toString('base64'),
    isBase64Encoded: true,
  };
};
