/* gc-scene — make a moving scene for somebody's friend, and report on one.
   ─────────────────────────────────────────────────────────────────────────
   POST { owner_key, portrait, where, seconds }  -> { job_id }
   GET  ?job_id=...                              -> { status, note, ready }
   GET  ?job_id=...&file=1                       -> the mp4 itself

   A friend you build comes with one still picture. This is what turns a
   picture into a scene, and it is the machinery behind the Scene two, three,
   four, five slots in the room.

   NO BACKGROUND FUNCTION, copied deliberately from etl-design-animate, which
   learned this the hard way: starting a Veo render is a sub-second call that
   returns an operation name, so POST does it directly, and GET polls that
   operation and finishes the job when it is done. Handing off to a background
   worker gave six runs in a row that reported 'running' and then sat on
   'queued' forever, because Netlify answered the invocation with 202 and never
   ran it. The thing that completes the job is the thing already asking about
   it, so there is no invocation left to fail silently.

   THEY HAVE TO LOOK UP. Dr. O rejected a finished clip of Arch doing woodwork
   for exactly one reason: "he never looked up. I could not have that for a
   companion video." A person absorbed in a task is footage of somebody who
   does not know you are there, and a scene is supposed to be somebody sitting
   WITH you. That instruction is added to every prompt here rather than left to
   whoever writes the description, because getting it wrong costs a whole
   render and only shows up at the end.

   IT SPENDS REAL MONEY, SO IT IS OWNER ONLY. Veo Lite takes an input frame at
   five cents a second, which is the whole reason this is affordable, and the
   ladder in _veo-video.js steps up to the standard tier at forty if Lite
   refuses. Four seconds is twenty cents at best and a pound sixty at worst,
   per press. No visitor gets to spend that: scenes are sold and then made,
   not generated by anybody who finds the endpoint.
*/

