/* ─────────────────────────────────────────────────────────────────────────────
   studio-chris-wardrobe

   The fitting room. Read side of Chris's tailor shop (Basic auth, PRESS_ADMIN):

     ?pa=auggie            -> tiny HTML contact sheet: status + all outfits inline
     ?pa=auggie&list=1     -> raw index JSON (status per outfit)
     ?pa=auggie&i=3        -> outfit #3 as a PNG (right-click, save as)

   Images are generated by studio-chris-wardrobe-background.js into the
   'pa_wardrobe' blob store. Terry saves the keepers and builds the wide
   Zoom frames in Photoshop.
   ───────────────────────────────────────────────────────────────────────── */

const { getStore, connectLambda } = require('@netlify/blobs');

function checkAdminAuth(event) {
  const expectedUser = process.env.PRESS_ADMIN_USER;
  const expectedPass = process.env.PRESS_ADMIN_PASS;
  if (!expectedUser || !expectedPass) return false;
  const header = (event.headers && (event.headers.authorization || event.headers.Authorization)) || '';
  if (!header.toLowerCase().startsWith('basic ')) return false;
  const decoded = Buffer.from(header.slice(6), 'base64').toString('utf8');
  const [u, p] = decoded.split(':');
  return u === expectedUser && p === expectedPass;
}

exports.handler = async (event) => {
  if (!checkAdminAuth(event)) {
    return { statusCode: 401, headers: { 'WWW-Authenticate': 'Basic realm="wardrobe"' }, body: 'unauthorized' };
  }
  try { connectLambda(event); } catch (_) {}

  const params = event.queryStringParameters || {};
  const pa = (params.pa || '').toLowerCase().trim();
  if (!pa) return { statusCode: 400, body: 'pa required, e.g. ?pa=auggie' };

  const store = getStore('pa_wardrobe');

  // Single image
  if (params.i) {
    const n = parseInt(params.i, 10);
    const buf = await store.get(pa + '/' + n + '.png', { type: 'arrayBuffer' });
    if (!buf) return { statusCode: 404, body: 'not generated yet' };
    return {
      statusCode: 200,
      headers: { 'Content-Type': 'image/png', 'Cache-Control': 'no-store', 'Content-Disposition': 'inline; filename="' + pa + '-outfit-' + n + '.png"' },
      body: Buffer.from(buf).toString('base64'),
      isBase64Encoded: true,
    };
  }

  const index = await store.get(pa + '/index', { type: 'json' });
  if (!index) return { statusCode: 404, body: 'no run yet for ' + pa + '; trigger studio-chris-wardrobe-background?pa=' + pa };

  // Raw status JSON
  if (params.list) {
    return { statusCode: 200, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }, body: JSON.stringify(index, null, 2) };
  }

  // Contact sheet
  const cells = (index.outfits || []).map(o => {
    const ok = o.status === 'done';
    return '<div style="background:#fff;border:1px solid #ddd;padding:10px;">'
      + (ok ? '<a href="?pa=' + pa + '&i=' + o.n + '" target="_blank"><img src="?pa=' + pa + '&i=' + o.n + '" style="width:100%;display:block;"></a>' : '<div style="aspect-ratio:1;display:flex;align-items:center;justify-content:center;background:#f5f2ea;color:#a00;font:12px monospace;padding:10px;text-align:center;">' + o.status + '</div>')
      + '<div style="font:11px monospace;margin-top:8px;color:#555;">#' + o.n + ' &middot; ' + o.outfit + '</div></div>';
  }).join('');
  const html = '<!doctype html><meta charset="utf-8"><title>' + (index.name || pa) + ' wardrobe</title>'
    + '<body style="background:#faf7f1;font-family:Georgia,serif;padding:30px;max-width:1300px;margin:0 auto;">'
    + '<h1 style="font-size:22px;">' + (index.name || pa) + ' &middot; the wardrobe (' + (index.quality || 'medium') + ')</h1>'
    + '<p style="font:13px monospace;color:#777;">started ' + (index.started_at || '') + (index.finished_at ? ' &middot; finished ' + index.finished_at : ' &middot; still running, refresh me') + '. Click an image to open full size, then right-click, save as.</p>'
    + '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:14px;">' + cells + '</div></body>';
  return { statusCode: 200, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' }, body: html };
};
